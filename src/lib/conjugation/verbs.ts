function parse([inf, en, flags = "", extra = {}]: Row, rank: number): VerbSpec & { rank: number } {
  const f = flags.split(" ").filter(Boolean);
  const spec: VerbSpec & { rank: number } = { inf, en, rank, ...extra };
  for (const flag of f) {
    if (flag === "ie" || flag === "ue" || flag === "i" || flag === "u>ue" || flag === "i>ie") spec.sc = flag;
    else if (flag === "acc") spec.acc = true;
    else if (flag === "nozc") spec.zc = false;
    else if (flag === "y") spec.y = true;
    else if (flag === "prn") spec.prn = "also";
    else if (flag === "prn!") spec.prn = "only";
    else throw new Error(`verbs.ts: unknown flag "${flag}" on ${inf}`);
  }
  return spec;
}

/** Every verb the engine knows, most frequent first. `rank` starts at 1. */
export const VERB_SPECS: (VerbSpec & { rank: number })[] = ROWS.map((row, i) => parse(row, i + 1));
