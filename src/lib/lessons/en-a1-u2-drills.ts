const SECONDS: Record<string, number> = {
  "multiple-choice": 15, "multi-select": 20, "listen-choose": 20, "fill-blank": 20, translate: 30,
  "word-order": 25, matching: 30, dictation: 30, speak: 25, write: 0,
};
const tr = (source: string, answer: string, explanation: string, altAnswers?: string[]): Exercise => ({
  type: "translate", direction: "es-en", prompt: "Traduce al inglés.", source, answer, ...(altAnswers ? { altAnswers } : {}), explanation,
});
const fb = (sentence: string, answer: string, en: string, explanation: string, altAnswers?: string[]): Exercise => ({
  type: "fill-blank", prompt: "Escribe en inglés las palabras en negrita.", sentence, answer, en, ...(altAnswers ? { altAnswers } : {}), explanation,
});
const mc = (question: string, options: string[], correctIndex: number, explanation: string): Exercise => ({
  type: "multiple-choice", question, options, correctIndex, explanation,
});
const lc = (audio: string, question: string, options: string[], correctIndex: number, explanation: string): Exercise => ({
  type: "listen-choose", audio, question, options, correctIndex, explanation,
});
const heard = (audio: string, options: string[], explanation: string): Exercise =>
  lc(audio, "¿Qué palabra has oído?", options, options.indexOf(audio), explanation);
const dc = (audio: string, explanation: string, altAnswers?: string[]): Exercise => ({
  type: "dictation", audio, ...(altAnswers ? { altAnswers } : {}), explanation,
});
const sp = (text: string, explanation: string, tip: string, prompt?: string): Exercise => ({
  type: "speak", text, ...(prompt ? { prompt } : {}), tip, explanation,
});
const mt = (instructions: string, pairs: [string, string][], explanation: string): Exercise => ({
  type: "matching", instructions, pairs: pairs.map(([left, right]) => ({ left, right })), explanation,
});
const drill = (
  n: number,
  title: string,
  summary: string,
  recap: { heading: string; body: string[]; examples: [string, string][] },
  exercises: Exercise[]
): Lesson => {
  const seconds = exercises.reduce((sum, e) => sum + SECONDS[e.type], 60);
  return {
    slug: `en-a1-sounds-unit-drill-${n}`,
    level: "EN-A1",
    number: n,
    title: `Entrenamiento: ${title}`,
    summary,
    duration: `${Math.round(seconds / 60)} min`,
    sections: [{ heading: recap.heading, body: recap.body, examples: recap.examples.map(([es, en]) => ({ es, en })) }],
    exercises,
  };
};

